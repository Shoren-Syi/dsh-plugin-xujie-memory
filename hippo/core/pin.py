"""钉住（M16.2）：用户说"记住这个"，那件事就永不衰减、永远在场。

## 为什么用规则而不是模型

判"这句话是不是在要求记住"看起来很适合交给模型，但**这是一条每分钟都会
走的路径**（每轮对话的 user 消息都要过一遍）。为它加一次 API 调用等于把
约束⑤（成本必须低）当场推翻。

规则能到这个准确率，是因为中文里"要求记住"是一个**祈使句**，
而祈使句有稳定的形态：`记住/记一下/别忘了/一定要记得`。真正会误判的是
陈述句 `我记得你说过` 和疑问句 `你还记得吗`——这两类都不含祈使标记。

## 为什么要一条否定表

    "不用记住这个，随口一说"     ← 含"记住"，但不是要钉
    "别记这个"                  ← 含"记"

否定先于肯定判断：命中否定表直接返回 False，不再看祈使标记。
顺序反了的话，`不用记住` 会因为含 `记住` 而被判成"要钉"——
**这正是 M15 那个 `frozen` bug 的同一种错法：只查了正向条件。**

## 钉住的代价是恒定的，所以要有上限

pinned 事件永不衰减、永远进 C 段。一条不贵，20 条就是 500 token/轮，
比整个 D 段还大。所以 C 段超预算时提醒用户清理一次（`warn_once`），
提醒过就不再提——**反复提醒会变成噪声，用户会连看都不看**。
"""

from __future__ import annotations

import re

# 祈使标记。"记得"单独不算：`我记得`/`你还记得吗` 都是陈述或疑问。
PIN_MARKERS = (
    # 裸"记住"先放：它覆盖 记住这个/记住：/记住我 等所有变体。
    # 剩下的条目是**同样意思但不含"记住"二字**的说法。
    "记住",
    "你要记住", "你记住", "请记住", "帮我记住",
    "记一下", "记下来", "记一下这个", "存一下",
    "别忘了", "不要忘了", "别忘记", "不要忘记",
    "一定要记得", "一定要记住", "必须记住", "必须记得", "一定要记",
    "这个重要", "这很重要", "很重要记得",
)

# 否定先判。命中即不钉。
_NEG = (
    "不用记", "不用记住", "不需要记", "没必要记", "别记这个",
    "不用记下来", "随便说说", "只是随口",
)

# 带"记住"但其实是别的意思。裸"记住"进了 marker 表之后，这几条必须挡——
# 否则"我记住了"（应答）和"你记住密码了吗"（提问）都会被钉住。
#
# 这里踩过一个坑：第一版写的是 `"我记住"`，结果 `"帮我记住"` 也被挡掉了
# （子串命中）。**否定/排除表里放得太短，会误伤它自己的反例。**
# 所以这几条都带上了"了/过/吗"这类收尾，只匹配完整的说法。
_FALSE_FRIENDS = (
    "记住密码了吗", "记住了吗", "我记住了", "我记住过", "记住过",
)


def looks_pinned(text: str) -> bool:
    """这句话是不是在要求"记住"。

    只判祈使，不判内容：用户说"记住我讨厌香菜"和"记住明天开会"都算，
    钉的是"这件事"，不需要理解它是哪一类事。
    """
    t = (text or "").strip()
    if not t:
        return False
    if any(n in t for n in _NEG):
        return False
    if any(f in t for f in _FALSE_FRIENDS):
        return False
    return any(m in t for m in PIN_MARKERS)


def pin_span(text: str) -> str:
    """把命中的那句抠出来，给日志和 `hippo pin --list` 用。

    抠不出来就返回空串——日志里写"用户说了要记住"但不写哪句话，
    等于没法排查误判。
    """
    t = (text or "").strip()
    if not looks_pinned(t):
        return ""
    parts = re.split(r"[。！？\n]", t)
    for p in parts:
        if any(m in p for m in PIN_MARKERS):
            return p.strip()[:80]
    return t[:80]
