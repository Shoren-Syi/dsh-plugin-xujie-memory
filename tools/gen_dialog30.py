"""30 天模拟对话数据集（M15.1 的验收基础）。

## 为什么必须自己造，而且必须造得"不规整"

手册 DoD：「跑 30 天模拟数据后，近似重复事件占比从 18% 降到 <5%」。
这句话的成败全在**数据集长什么样**。

真机库（44 条）不能用来验这个：它的 6 条"不吃辣"是测试脚本在同一秒写进去的，
关键词几乎逐字相同。拿它验收，任何判据都会很好看，然后上线后一条都合并不了。

真实的重复长这样：

    第 3 天  "我昨天搬家了，从朝阳搬到海淀，房租涨了两千"
    第 11 天 "上次说的搬家那事，我从朝阳挪到海淀了"
    第 25 天 "搬家真是累，不过房租涨两千还行"

三次说的都是同一件事，但**关键词只重合 1~2 个**。这就是为什么手册那个
「关键词 Jaccard × 0.6 + 摘要 trigram × 0.4，阈值 0.75」在真数据上会归零。

所以这个生成器刻意做三件事：

1. **措辞库**：每个话题 2~5 种说法，随机取。同一件事三次提，用词可以完全不同。
2. **关键词抽稀**：每次从话题的核心词里**随机取 2~4 个**（模拟抽取器的波动），
   而不是给全量。两条同话题事件的词集合可能只交 1 个。
3. **故意制造难例**：
   - 更正型（"住朝阳" → "说错了，是海淀"）——共享「居住」，绝不该合并
   - 状态变化（"想辞职" → "先忍着"）——共享「辞职」，绝不该合并
   - 干扰实体（"老王" 出现在出差/来访两个话题里）

`truth` 字段就是 ground truth：每条事件属于哪个话题（`None` = 独立事件）。
合并算法的成绩单 = 有多少同话题事件被判成同簇、有多少跨话题事件被误合。

## 一个造数据踩过的坑（留着当警示）

第一版 filler 用 `FILLERS[i % len(FILLERS)]` 循环，60 条 filler 只有 10 种文本，
"地铁今天特别挤"被写了 6 遍。而标注里它们 `truth=None`（不同事件）——
**算法把 6 条逐字相同的判成一簇，反而被记成 6 次误合并**。

那次跑出来"误合 55/57"，看着像判据全错，其实是数据造错了。
现在的 filler 由 `_WHEN × _WHAT × _MOD` 组合生成，保证互不相同
（组合空间 1260，用 100 条不重复），`_fillers()` 里有 assert 兜底。

用法：
    python3 -m tools.gen_dialog30 --out tests/fixtures/dialog_30d.jsonl --seed 7
    python3 -m tools.gen_dialog30 --stats        # 只看统计，不写文件
"""

