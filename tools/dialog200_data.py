"""M26.1 · 200 轮长对话语料的**数据部分**。

## 为什么针要分两种

50 条"事实针"如果全写成 `fact`，评测就只测到 facts 表一条通路。
而系统里有两套记忆：**事实**是"当前状态"（住在哪个城市、什么工作），
**事件**是"发生过什么"（老王是前同事、我妈查出高血压）。

- 事实走 `facts` 表，key 必须落在闭集词表里（`hippo/data/fact_keys.yaml`）。
  所以 15 条个人信息严格映射到表内 key，一个都不能自造——
  自造的 key 会被 `set_fact` 静默拒收，评测就会显示"存进去了但查不到"，
  而真正的原因在语料。
- 关系 / 偏好 / 计划 / 伏笔走 events + entities + traits。它们本来就
  不该进 fact 表："老王是前同事"不是一条可被覆盖的当前状态。

## 为什么脚本生成 + 人工台词

手册说"不要纯模型生成——模型写的对话太顺，测不出真实问题"。这份数据
的全部台词是手写的，脚本只负责组装和校验。手写才能故意留下这些东西：

- 一句话里两件事（"我现在住杭州城西，房租6500"）
- 同一件事换了说法再提（第 1 段"下个月搬家"，第 5 段"搬家公司定了"）
- 中间插一大堆无关闲聊，把针埋到检索容易漏的深度
- 用户自己说错、含糊、指代不明（"那边"、"那个手术"）

## 5 段的分法

搬居 / 工作 / 家人健康 / 朋友社交 / 计划收尾。段与段之间不是硬切，
后段会回头引用前段（跨段引用 ≥20 处），这是长对话和五段短对话的区别：
真正的长对话里，第 170 轮会突然回到第 8 轮说过的事。
"""
